export function jobTypeKey(type: JobType): TranslationKey {
  return JOB_TYPE_KEYS[type];
}

export function statusKey(status: ApplicationStatus): TranslationKey {
  return STATUS_KEYS[status];
}

// A location we have no translation for is shown as the company wrote it.
export function cityKey(name: string | null | undefined): string {
  if (!name) return "";
  return CITY_KEYS[name] ?? name;
}
